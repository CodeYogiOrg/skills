/**
 * Audio → typed SubtitleScreen data file, one command.
 *
 * Wraps mlx_whisper (word-level timestamps), trims the leading space in each
 * word, applies an optional global offset (e.g. −0.9s when the audio mounts
 * before the scene), rounds to 2 dp and emits src/data/<name>.ts ready to
 * import. Re-run any time a mount shifts — regeneration is free.
 *
 * The emitted TEXT is whisper's raw guess. The user-approved mixed style
 * (Hindi in Devanagari, brands in Roman — वाट्सएप → WhatsApp) is still a
 * CONTENT step: fix the `word` fields after generation, timings stay.
 *
 * Usage:
 *   node scripts/transcribe.mjs public/audio/section-3.mp3 \
 *     --var S3_LINE1_WORDS --out src/data/subtitle-s3-line1.ts \
 *     [--offset -0.9] [--from 1.2] [--to 6.64] [--language hi]
 *
 * --from/--to (seconds, in SOURCE time, before offset) select one line's
 * words out of a section clip. Omit to emit every word.
 * Prints the speech span + inter-word silence gaps ≥0.3s to stdout — use
 * these for SPEECH_WINDOWS ducking and line-boundary midpoints.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";

const WHISPER = join(homedir(), "Library/Python/3.9/bin/mlx_whisper");

const args = process.argv.slice(2);
const audio = args.find((a) => !a.startsWith("--"));
const val = (flag, dflt) => {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : dflt;
};
if (!audio) {
  console.error("Usage: node scripts/transcribe.mjs <audio> --var NAME --out src/data/name.ts [--offset s] [--from s] [--to s] [--language hi]");
  process.exit(1);
}

const varName = val("--var", "WORDS");
const out = val("--out", `src/data/${basename(audio).replace(/\.[^.]+$/, "")}.ts`);
const offset = parseFloat(val("--offset", "0"));
const from = parseFloat(val("--from", "-Infinity"));
const to = parseFloat(val("--to", "Infinity"));
const language = val("--language", "hi");

const scratch = join(tmpdir(), `transcribe-${basename(audio)}-${process.pid}`);
mkdirSync(scratch, { recursive: true });
execFileSync(
  WHISPER,
  [
    audio,
    "--model", "mlx-community/whisper-large-v3-turbo",
    "--word-timestamps", "True",
    "--output-format", "json",
    "--output-dir", scratch,
    "--language", language,
  ],
  { stdio: ["ignore", "inherit", "inherit"] },
);

const jsonFile = join(scratch, basename(audio).replace(/\.[^.]+$/, ".json"));
const data = JSON.parse(readFileSync(jsonFile, "utf8"));
rmSync(scratch, { recursive: true, force: true });

const all = data.segments.flatMap((s) => s.words ?? []);
const r2 = (n) => Math.round(n * 100) / 100;
const words = all
  .filter((w) => w.start >= from && w.start < to)
  .map((w) => ({ word: w.word.trim(), start: r2(w.start + offset), end: r2(w.end + offset) }))
  .filter((w) => w.word.length > 0);

if (words.length === 0) {
  console.error("No words in the selected range — check --from/--to.");
  process.exit(1);
}

// Silence gaps (source time) — line boundaries + ducking windows come from these.
const gaps = [];
for (let i = 1; i < all.length; i++) {
  const gap = all[i].start - all[i - 1].end;
  if (gap >= 0.3) {
    gaps.push(
      `  ${r2(all[i - 1].end)}s → ${r2(all[i].start)}s  (${r2(gap)}s after "${all[i - 1].word.trim()}", midpoint ${r2((all[i - 1].end + all[i].start) / 2)}s)`,
    );
  }
}

const lines = words
  .map((w) => `  { word: ${JSON.stringify(w.word)}, start: ${w.start}, end: ${w.end} },`)
  .join("\n");
const rangeNote =
  Number.isFinite(from) || Number.isFinite(to)
    ? ` (source ${Number.isFinite(from) ? from : 0}–${Number.isFinite(to) ? to : "end"}s)`
    : "";
const offsetNote = offset !== 0 ? `, SHIFTED ${offset > 0 ? "+" : ""}${offset}s` : "";

writeFileSync(
  out,
  `import type { SubtitleWord } from "../components/SubtitleScreen";

// Generated by scripts/transcribe.mjs from ${basename(audio)}${rangeNote}${offsetNote}.
// Timings: whisper word-level. TEXT is whisper's raw guess — apply the
// user-approved mixed style by hand (brands in Roman), timings stay.
export const ${varName}: SubtitleWord[] = [
${lines}
];
`,
);

console.log(`\nWrote ${out} — ${words.length} words, ${varName}`);
console.log(`Speech span (source time): ${r2(all[0].start)}s → ${r2(all[all.length - 1].end)}s`);
console.log(gaps.length ? `Silence gaps ≥0.3s:\n${gaps.join("\n")}` : "No silence gaps ≥0.3s.");
